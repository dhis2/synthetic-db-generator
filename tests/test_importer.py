from dbgen.dhis2 import importer


def test_without_drops_the_fields_from_attributes_and_data_values():
    payload = {
        "trackedEntities": [
            {
                "attributes": [
                    {"attribute": "age", "value": "25"},
                    {"attribute": "name", "value": "A"},
                ],
                "enrollments": [
                    {
                        "attributes": [{"attribute": "age", "value": "25"}],
                        "events": [
                            {"dataValues": [{"dataElement": "date", "value": "2021-01-01"},
                                            {"dataElement": "hb", "value": "11"}]}
                        ],
                    }
                ],
            }
        ]
    }  # fmt: skip
    out = importer.without(payload, {"age", "date"})
    te = out["trackedEntities"][0]
    assert te["attributes"] == [{"attribute": "name", "value": "A"}]
    assert te["enrollments"][0]["attributes"] == []
    assert te["enrollments"][0]["events"][0]["dataValues"] == [{"dataElement": "hb", "value": "11"}]


def test_a_tally_counts_by_code_rule_and_field():
    names = {"Rule0000001": ("rule", "C: Age"), "Field000001": ("field", "Age")}
    tally = importer.Tally()
    for _ in range(2):
        tally.add("E1309", "Generated by ProgramRule (`Rule0000001`) - `Field000001`", names)
    [row] = tally.rows(names)
    assert (row["code"], row["rule"], row["field"], row["count"]) == (
        "E1309",
        "Rule0000001",
        "Field000001",
        2,
    )
